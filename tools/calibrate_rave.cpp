// Sets the output trim of every rave preset so its peak sits near 0.7 (dance master off). Usage: calibrate_rave > presets/presets_rave_gain.h
#include "../presets/presets.h"
#include <cstdio>
using namespace supurr;
static double peakOf(Engine& e, int note, float hold, float total) {
  e.p.dmMix = 0.f; e.prepare(48000); e.noteOn(note, 0.9f); float lb[64], rb[64]; size_t N = (size_t)(total * 48000); double pk = 0;
  for (size_t pos = 0; pos < N; pos += 64) {
    if (pos >= (size_t)(hold * 48000) && pos < (size_t)(hold * 48000) + 64) e.noteOff(note);
    e.render(lb, rb, 64); for (int i = 0; i < 64; ++i) pk = std::max(pk, (double)std::max(std::fabs(lb[i]), std::fabs(rb[i])));
  }
  return pk;
}
int main() {
  int n; const presets::RaveEntry* L = presets::raveList(n);
  std::printf("// Generated by tools/calibrate_rave.cpp: output trim per rave preset. Do not edit by hand.\n#pragma once\nstruct RaveGain { const char* name; float gain; };\nstatic const RaveGain kRaveGain[] = {\n");
  for (int i = 0; i < n; ++i) {
    float g = 1.f;
    for (int it = 0; it < 5; ++it) { Engine e; L[i].fn(e.p); e.p.master *= g; double pk = peakOf(e, L[i].note, L[i].hold, L[i].total); if (pk < 1e-4) break; g *= (float)(0.7 / pk); g = std::max(0.02f, std::min(12.f, g)); }
    std::printf("  {\"%s\", %.4f},\n", L[i].name, g);
  }
  std::printf("  {\"\", 1.f}};\n"); return 0;
}
